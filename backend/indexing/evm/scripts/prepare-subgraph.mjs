#!/usr/bin/env node
/**
 * Prepare subgraph.yaml + src/addresses.ts + abis/ from Hardhat artifacts.
 *
 * Usage (from backend/indexing/evm):
 *   pnpm configure
 *
 * Env (optional — auto-read from ignition/deployments when present):
 *   SUBGRAPH_NETWORK=sepolia
 *   SUBGRAPH_START_BLOCK=12345678
 *   CRYPTOPETS_ADDRESS=0x...
 *   SEPOLIA_RPC_URL / SUBGRAPH_RPC_URL — to resolve battleLogic + inventory
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createPublicClient, http } from 'viem';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SUBGRAPH_DIR = path.join(__dirname, '..');
const CONTRACTS_DIR = path.join(SUBGRAPH_DIR, '..', '..', '..', '..', 'contracts', 'ethereum');
const ARTIFACTS = path.join(CONTRACTS_DIR, 'artifacts', 'src');

loadEnvFile(path.join(CONTRACTS_DIR, '.env'));

function loadEnvFile(envPath) {
    if (!fs.existsSync(envPath)) return;
    for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eq = trimmed.indexOf('=');
        if (eq === -1) continue;
        const key = trimmed.slice(0, eq).trim();
        const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
        if (process.env[key] == null || process.env[key] === '') {
            process.env[key] = value;
        }
    }
}

const ZERO = '0x0000000000000000000000000000000000000000';

const cryptoPetsAbi = [
    {
        type: 'function',
        name: 'battleLogic',
        inputs: [],
        outputs: [{ type: 'address' }],
        stateMutability: 'view',
    },
    {
        type: 'function',
        name: 'inventory',
        inputs: [],
        outputs: [{ type: 'address' }],
        stateMutability: 'view',
    },
] ;

function readJson(p) {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function copyAbi(contractName, destName = contractName) {
    const src = path.join(ARTIFACTS, `${contractName}.sol`, `${contractName}.json`);
    if (!fs.existsSync(src)) {
        throw new Error(
            `Missing artifact ${src}. Run "pnpm compile" in contracts/ethereum first.`
        );
    }
    const { abi } = readJson(src);
    const outDir = path.join(SUBGRAPH_DIR, 'abis');
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, `${destName}.json`), JSON.stringify(abi, null, 2));
}

function loadIgnitionAddress(network) {
    const chainIds = { sepolia: 11155111, mainnet: 1, localhost: 31337, hardhat: 31337 };
    const chainId = chainIds[network];
    if (!chainId) return null;

    const deployedPath = path.join(
        CONTRACTS_DIR,
        'ignition',
        'deployments',
        `chain-${chainId}`,
        'deployed_addresses.json'
    );
    if (!fs.existsSync(deployedPath)) return null;

    const deployed = readJson(deployedPath);
    return (
        deployed['CryptoPetsLive#cryptoPets'] ??
        deployed['CryptoPetsSepolia#CryptoPets'] ??
        deployed['CryptoPetsSepolia#cryptoPets'] ??
        null
    );
}

function resolveRpcUrl(network) {
    if (process.env.SUBGRAPH_RPC_URL) return process.env.SUBGRAPH_RPC_URL;
    const prefix = network.toUpperCase().replace(/-/g, '_');
    return (
        process.env[`${prefix}_RPC_URL`] ??
        process.env[`${prefix}_URL`] ??
        process.env.SEPOLIA_RPC_URL ??
        process.env.SEPOLIA_URL ??
        null
    );
}

async function resolveChildAddresses(cryptoPetsAddress, rpcUrl) {
    if (!rpcUrl || !cryptoPetsAddress || cryptoPetsAddress === ZERO) {
        return { battle: ZERO, inventory: ZERO };
    }

    const client = createPublicClient({ transport: http(rpcUrl) });
    const [battle, inventory] = await Promise.all([
        client.readContract({
            address: cryptoPetsAddress,
            abi: cryptoPetsAbi,
            functionName: 'battleLogic',
        }),
        client.readContract({
            address: cryptoPetsAddress,
            abi: cryptoPetsAbi,
            functionName: 'inventory',
        }),
    ]);

    return { battle, inventory };
}

function writeAddressesTs(cryptoPetsAddress) {
    const content = `// Generated by scripts/prepare-subgraph.mjs — do not edit by hand.
import { Address } from "@graphprotocol/graph-ts";

export const CRYPTOPETS_ADDRESS = Address.fromString("${cryptoPetsAddress.toLowerCase()}");
`;
    fs.writeFileSync(path.join(SUBGRAPH_DIR, 'src', 'addresses.ts'), content);
}

function writeSubgraphYaml(vars) {
    const template = fs.readFileSync(
        path.join(SUBGRAPH_DIR, 'subgraph.template.yaml'),
        'utf8'
    );
    let yaml = template;
    for (const [key, value] of Object.entries(vars)) {
        yaml = yaml.replaceAll(`{{${key}}}`, String(value));
    }
    fs.writeFileSync(path.join(SUBGRAPH_DIR, 'subgraph.yaml'), yaml);
}

async function main() {
    const network = process.env.SUBGRAPH_NETWORK ?? 'sepolia';
    const startBlock = process.env.SUBGRAPH_START_BLOCK ?? '0';

    let cryptoPetsAddress =
        process.env.CRYPTOPETS_ADDRESS ??
        loadIgnitionAddress(network) ??
        ZERO;

    cryptoPetsAddress = cryptoPetsAddress.toLowerCase();

    copyAbi('CryptoPets');
    copyAbi('Battle');
    copyAbi('Inventory');

    const rpcUrl = resolveRpcUrl(network);
    let battleAddress = ZERO;
    let inventoryAddress = ZERO;

    try {
        const child = await resolveChildAddresses(cryptoPetsAddress, rpcUrl);
        battleAddress = (child.battle ?? ZERO).toLowerCase();
        inventoryAddress = (child.inventory ?? ZERO).toLowerCase();
    } catch (err) {
        console.warn(
            `[subgraph] Could not resolve battleLogic/inventory via RPC: ${err.message}`
        );
    }

    writeAddressesTs(cryptoPetsAddress);
    writeSubgraphYaml({
        NETWORK: network,
        CRYPTOPETS_ADDRESS: cryptoPetsAddress,
        BATTLE_ADDRESS: battleAddress,
        INVENTORY_ADDRESS: inventoryAddress,
        START_BLOCK: startBlock,
    });

    console.log('[subgraph] Prepared subgraph.yaml');
    console.log(`  network:          ${network}`);
    console.log(`  startBlock:       ${startBlock}`);
    console.log(`  CryptoPets:       ${cryptoPetsAddress}`);
    console.log(`  Battle:           ${battleAddress}`);
    console.log(`  Inventory:        ${inventoryAddress}`);

    if (cryptoPetsAddress === ZERO) {
        console.warn(
            '\n⚠️  CRYPTOPETS_ADDRESS is not set. Set CRYPTOPETS_ADDRESS or deploy to sepolia first,\n' +
                '   then re-run: pnpm prepare'
        );
    }
    if (startBlock === '0') {
        console.warn(
            '⚠️  SUBGRAPH_START_BLOCK=0 syncs from genesis (slow). Set it to your contract deploy block.'
        );
    }
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
