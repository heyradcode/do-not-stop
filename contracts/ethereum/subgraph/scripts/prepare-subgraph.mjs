#!/usr/bin/env node
/**
 * Prepare subgraph.yaml + src/addresses.ts + abis/ for the v2 stack.
 *
 * Usage (from contracts/ethereum/subgraph):
 *   pnpm configure
 *
 * Env (optional — proxy addresses auto-read from ignition/deployments when present):
 *   SUBGRAPH_NETWORK=sepolia
 *   SUBGRAPH_START_BLOCK=12345678     # the v2 deploy block (the indexer reindexes from here)
 *   PETCORE_ADDRESS=0x...             # PetCoreV1 proxy
 *   GAMELOGIC_ADDRESS=0x...           # GameLogicV1 proxy
 *
 * The v2 stack (PetCoreV1 + GameLogicV1) is two UUPS proxies — index the proxy
 * addresses, not the implementations. See ignition/modules/CryptoPetsV2Live.ts.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SUBGRAPH_DIR = path.join(__dirname, '..');
// subgraph/ lives directly under contracts/ethereum
const CONTRACTS_DIR = path.join(SUBGRAPH_DIR, '..');
const ARTIFACTS = path.join(CONTRACTS_DIR, 'artifacts', 'src');

loadEnvFile(path.join(CONTRACTS_DIR, '.env'));

function loadEnvFile(envPath) {
    if (!fs.existsSync(envPath)) return;
    for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eq = trimmed.indexOf('=');
        if (eq === -1) continue;
        const key = trimmed.slice(0, eq).trim();
        const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
        if (process.env[key] == null || process.env[key] === '') {
            process.env[key] = value;
        }
    }
}

const ZERO = '0x0000000000000000000000000000000000000000';

function readJson(p) {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function copyAbi(contractName, destName = contractName) {
    const src = path.join(ARTIFACTS, `${contractName}.sol`, `${contractName}.json`);
    if (!fs.existsSync(src)) {
        throw new Error(
            `Missing artifact ${src}. Run "pnpm compile" in contracts/ethereum first.`
        );
    }
    const { abi } = readJson(src);
    const outDir = path.join(SUBGRAPH_DIR, 'abis');
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, `${destName}.json`), JSON.stringify(abi, null, 2));
}

// Reads a proxy address from the ignition deployment for the given module key.
function loadIgnitionAddress(network, key) {
    const chainIds = { sepolia: 11155111, mainnet: 1, base: 8453, 'base-sepolia': 84532, localhost: 31337, hardhat: 31337 };
    const chainId = chainIds[network];
    if (!chainId) return null;

    const deployedPath = path.join(
        CONTRACTS_DIR,
        'ignition',
        'deployments',
        `chain-${chainId}`,
        'deployed_addresses.json'
    );
    if (!fs.existsSync(deployedPath)) return null;

    return readJson(deployedPath)[key] ?? null;
}

function writeAddressesTs(petCoreAddress, gameLogicAddress) {
    const content = `// Generated by scripts/prepare-subgraph.mjs — do not edit by hand.
import { Address } from "@graphprotocol/graph-ts";

export const PETCORE_ADDRESS = Address.fromString("${petCoreAddress.toLowerCase()}");
export const GAMELOGIC_ADDRESS = Address.fromString("${gameLogicAddress.toLowerCase()}");
`;
    fs.writeFileSync(path.join(SUBGRAPH_DIR, 'src', 'addresses.ts'), content);
}

function writeSubgraphYaml(vars) {
    const template = fs.readFileSync(
        path.join(SUBGRAPH_DIR, 'subgraph.template.yaml'),
        'utf8'
    );
    let yaml = template;
    for (const [key, value] of Object.entries(vars)) {
        yaml = yaml.replaceAll(`{{${key}}}`, String(value));
    }
    fs.writeFileSync(path.join(SUBGRAPH_DIR, 'subgraph.yaml'), yaml);
}

function main() {
    const network = process.env.SUBGRAPH_NETWORK ?? 'sepolia';
    const startBlock = process.env.SUBGRAPH_START_BLOCK ?? '0';

    const petCoreAddress = (
        process.env.PETCORE_ADDRESS ??
        loadIgnitionAddress(network, 'CryptoPetsV2Live#PetCoreV1Proxy') ??
        ZERO
    ).toLowerCase();

    const gameLogicAddress = (
        process.env.GAMELOGIC_ADDRESS ??
        loadIgnitionAddress(network, 'CryptoPetsV2Live#GameLogicV1Proxy') ??
        ZERO
    ).toLowerCase();

    copyAbi('PetCoreV1');
    copyAbi('GameLogicV1');

    writeAddressesTs(petCoreAddress, gameLogicAddress);
    writeSubgraphYaml({
        NETWORK: network,
        PETCORE_ADDRESS: petCoreAddress,
        GAMELOGIC_ADDRESS: gameLogicAddress,
        START_BLOCK: startBlock,
    });

    console.log('[subgraph] Prepared subgraph.yaml');
    console.log(`  network:     ${network}`);
    console.log(`  startBlock:  ${startBlock}`);
    console.log(`  PetCoreV1:   ${petCoreAddress}`);
    console.log(`  GameLogicV1: ${gameLogicAddress}`);

    if (petCoreAddress === ZERO || gameLogicAddress === ZERO) {
        console.warn(
            '\n⚠️  PETCORE_ADDRESS / GAMELOGIC_ADDRESS not resolved. Set them (or deploy\n' +
                '   CryptoPetsV2Live to the network) and re-run: pnpm configure'
        );
    }
    if (startBlock === '0') {
        console.warn(
            '⚠️  SUBGRAPH_START_BLOCK=0 syncs from genesis (slow). Set it to the v2 deploy block.'
        );
    }
}

main();
